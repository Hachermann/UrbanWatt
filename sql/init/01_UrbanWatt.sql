-- =====================================================================
-- 01 - Création du schéma urbanwatt et des 9 tables
--
-- Exécuté automatiquement par Docker au premier démarrage de la base
-- (ce dossier est monté dans /docker-entrypoint-initdb.d, voir
-- infra/docker-compose.yaml). Les scripts s'exécutent dans l'ordre de
-- leur nom : 01, 02, puis 03.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS urbanwatt;

-- Schéma par défaut de la base : dans pgAdmin, on peut écrire
-- « FROM clients » au lieu de « FROM urbanwatt.clients », sans SET search_path.
DO $$
BEGIN
    EXECUTE format('ALTER DATABASE %I SET search_path TO urbanwatt, public',
                   current_database());
END
$$;

SET search_path TO urbanwatt;

CREATE TABLE "stations" (
  "id_station" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "code_station" varchar(255) UNIQUE NOT NULL,
  "nom_station" varchar(255) NOT NULL,
  "ville" varchar(255) NOT NULL,
  "adresse" varchar(255) NOT NULL,
  "date_ouverture" date NOT NULL
);

CREATE TABLE "bornes" (
  "id_borne" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_station" int NOT NULL,
  "code_borne" varchar(255) UNIQUE NOT NULL,
  "puissance_kw" decimal NOT NULL,
  "connecteur" varchar(255) NOT NULL,
  "etat" varchar(255) NOT NULL
);

CREATE TABLE "clients" (
  "id_client" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "prenom" varchar(255) NOT NULL,
  "nom" varchar(255) NOT NULL,
  "email" varchar(255) NOT NULL,
  "ville" varchar(255) NOT NULL,
  "date_inscription" date NOT NULL
);

CREATE TABLE "vehicules" (
  "id_vehicule" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_client" int NOT NULL,
  "immatriculation" varchar UNIQUE NOT NULL,
  "marque" varchar NOT NULL,
  "modele" varchar NOT NULL,
  "capacite_batterie_kwh" decimal NOT NULL
);

CREATE TABLE "sessions_recharge" (
  "id_session" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_borne" int NOT NULL,
  "id_vehicule" int NOT NULL,
  "debut_session" timestamp NOT NULL,
  "fin_session" timestamp,
  "energie_kwh" decimal,
  "cout_eur" decimal,
  "statut" varchar(255) NOT NULL
);

CREATE TABLE "paiements" (
  "id_paiement" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_session" int NOT NULL,
  "date_paiement" timestamp NOT NULL,
  "montant_eur" decimal NOT NULL,
  "mode_paiement" varchar(255) NOT NULL,
  "statut" varchar(255) NOT NULL
);

CREATE TABLE "incidents" (
  "id_incident" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_borne" int NOT NULL,
  "date_signalement" timestamp NOT NULL,
  "date_resolution" timestamp,
  "categorie" varchar NOT NULL,
  "gravite" varchar NOT NULL,
  "statut" varchar NOT NULL,
  "description" text NOT NULL
);

CREATE TABLE "techniciens" (
  "id_technicien" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "prenom" varchar(255) NOT NULL,
  "nom" varchar(255) NOT NULL,
  "email" varchar(255) NOT NULL
);

CREATE TABLE "interventions" (
  "id_intervention" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_incident" int NOT NULL,
  "id_technicien" int NOT NULL,
  "date_debut" timestamp NOT NULL,
  "date_fin" timestamp,
  "statut" varchar NOT NULL,
  "compte_rendu" text NOT NULL
);

ALTER TABLE "vehicules" ADD FOREIGN KEY ("id_client") REFERENCES "clients" ("id_client") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "bornes" ADD FOREIGN KEY ("id_station") REFERENCES "stations" ("id_station") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "interventions" ADD FOREIGN KEY ("id_technicien") REFERENCES "techniciens" ("id_technicien") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "interventions" ADD FOREIGN KEY ("id_incident") REFERENCES "incidents" ("id_incident") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "sessions_recharge" ADD FOREIGN KEY ("id_vehicule") REFERENCES "vehicules" ("id_vehicule") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "sessions_recharge" ADD FOREIGN KEY ("id_borne") REFERENCES "bornes" ("id_borne") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "paiements" ADD FOREIGN KEY ("id_session") REFERENCES "sessions_recharge" ("id_session") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "incidents" ADD FOREIGN KEY ("id_borne") REFERENCES "bornes" ("id_borne") DEFERRABLE INITIALLY IMMEDIATE;
